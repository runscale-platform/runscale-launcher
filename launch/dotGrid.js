// Единая сетка точечных знаков витрины.
//
// Точка — след печатающего устройства. Знак, собранный из точек, читается
// показанием прибора, а не рисунком: витрина этим говорит то же, что говорит
// продукт — здесь считают.
//
// ⚠ Диаметр точки и шаг сетки заданы ЗДЕСЬ и в пикселях, а не в долях кегля.
// Причина названа на приёмке: пока каждый знак масштабировался своей высотой
// (скобки от `1.2em`, стрелка от `0.4rem`), точки выходили разного диаметра
// и с разным просветом — сетка читалась тремя разными сетками. Один диаметр
// и один шаг на всё: скобки, цифры показания, рамка кнопки. Меняешь число —
// меняешь у всех знаков разом, и это единственный способ его менять.
//
// Просвет между точками равен радиусу: STEP − 2·R = 1 px. Меньше — точки
// слипаются в линию и знак перестаёт быть точечным; больше — фигура
// рассыпается и угол не читается.
export const DOT_R = 1
export const DOT_STEP = 3

/**
 * На сколько петля знака трека опущена внутри своего рисунка: столько места
 * занимает половина стрелы, стоящей на верхней дорожке.
 *
 * Величина живёт здесь, а не в самом знаке, потому что её обязаны знать двое:
 * знак — чтобы опустить дугу, и показание внутри — чтобы добрать верхнее поле
 * на ту же величину. Иначе центр петли и центр строки расходятся ровно
 * на половину этого числа, и надпись стоит выше внутреннего радиуса дорожки.
 */
export const LOOP_LIFT = 7

/** Габарит фигуры шириной `cols` и высотой `rows` точек. */
export function extent(cols, rows) {
  return { w: (cols - 1) * DOT_STEP + 2 * DOT_R, h: (rows - 1) * DOT_STEP + 2 * DOT_R }
}

/** Координаты центров точек по клеткам сетки. */
export function place(cells) {
  return cells.map(([c, r]) => [c * DOT_STEP + DOT_R, r * DOT_STEP + DOT_R])
}

/**
 * Цифры показания: сетка 3×5, знакоместо шириной в четыре колонки
 * (три под цифру, одна под просвет). Набор полный от 0 до 9 — счётчик
 * бизнесов меняется сам, и вторая цифра не имеет права приехать другим
 * начертанием.
 *
 * Высота цифры (5 рядов) на два ряда ниже скобки (7 рядов) — скобка обнимает
 * показание сверху и снизу, как и положено скобке.
 */
const DIGITS = {
  0: ['111', '101', '101', '101', '111'],
  1: ['010', '110', '010', '010', '111'],
  2: ['111', '001', '111', '100', '111'],
  3: ['111', '001', '111', '001', '111'],
  4: ['101', '101', '111', '001', '001'],
  5: ['111', '100', '111', '001', '111'],
  6: ['111', '100', '111', '101', '111'],
  7: ['111', '001', '001', '001', '001'],
  8: ['111', '101', '111', '101', '111'],
  9: ['111', '101', '111', '001', '111'],
}

const DIGIT_COLS = 3
const DIGIT_ROWS = 5

/**
 * Прописные буквы той же сетки — подпись показания на витрине (D-1400, слово
 * Михаила 16.10: «надпись ранскеил тоже точками как и все остальное по тем же
 * правилам. и размер по высоте тоже как у цифр и молнии»). Пять рядов — высота
 * цифры и молнии; квадратный рисунок, как у цифр; знакоместо — ширина буквы
 * плюс колонка просвета.
 *
 * Ширина у буквы своя. В три колонки, как цифра, стоит то, что в три колонки
 * читается (Р, А, С, Е). Буквам с диагональю или ножкой дана четвёртая: И
 * в три колонки диагонали не имеет вовсе; К в три отличается от Н одной точкой;
 * Л в три читается П со сдвинутым верхом. Н идёт в четыре парой к И — у них
 * один рисунок зеркалом, и разная ширина читалась бы разными буквами.
 * Тот же приём — у латинских букв приборов `/join` Ультры (`DotGlyph.vue`).
 *
 * Набор — буквы, которые стоят на экране, а не алфавит: новое слово подписи
 * без своих букв ловит самопроверка (`verify-mini.mjs`), и буква заводится
 * здесь, в один рисунок для всех мест.
 */
export const LETTERS = {
  Р: ['111', '101', '111', '100', '100'],
  А: ['111', '101', '111', '101', '101'],
  Н: ['1001', '1001', '1111', '1001', '1001'],
  С: ['111', '100', '100', '100', '111'],
  К: ['1001', '1010', '1100', '1010', '1001'],
  Е: ['111', '100', '110', '100', '111'],
  И: ['1001', '1001', '1011', '1101', '1001'],
  Л: ['0111', '0101', '0101', '0101', '1101'],
  // Плашка «РАНСКЕИЛ | В ЭФИРЕ» на `/live` Ультры (ultra UL-22, UD-186; слово Михаила 16.10, 08:57: «ранскеил
  // из шторки gderost.ru точками и также напиши в эфире»). В — в три колонки, как Р, со сколами справа, чтобы
  // не читаться цифрой 8; Э — зеркало Е; Ф — в пять: у буквы кольцо и ножка насквозь, в три колонки кольца нет.
  В: ['110', '101', '110', '101', '110'],
  Э: ['111', '001', '011', '001', '111'],
  Ф: ['00100', '11111', '10101', '11111', '00100'],
}

/**
 * Строка знаков подряд: знакоместо — ширина знака плюс колонка просвета.
 * Знак, которого нет в таблице (пробел-разделитель тысяч, пробел между
 * словами), занимает знакоместо `blank` колонок пустым — иначе разряды
 * и слова слипнутся.
 */
function runShape(chars, glyphOf, blank, minCols) {
  const cells = []
  let x = 0
  chars.forEach((ch) => {
    const rows = glyphOf(ch)
    if (rows) {
      rows.forEach((row, r) => {
        row.split('').forEach((v, c) => {
          if (v === '1') cells.push([x + c, r])
        })
      })
    }
    x += (rows ? rows[0].length : blank) + 1
  })
  const cols = Math.max(minCols, x - 1)
  const { w, h } = extent(cols, DIGIT_ROWS)
  return { w, h, dots: place(cells) }
}

/**
 * Фигура числа. Знакоместо цифры — четыре колонки (три под цифру, одна
 * под просвет); нецифровые знаки (пробел-разделитель тысяч) занимают его
 * пустым.
 */
export function numberShape(text) {
  return runShape(String(text).split(''), (ch) => DIGITS[ch], DIGIT_COLS, DIGIT_COLS)
}

/**
 * Фигура слова прописными из `LETTERS`, высота — пять рядов, как у цифры.
 * Пробел — пустое знакоместо в три колонки.
 */
export function wordShape(text) {
  const chars = String(text).toLocaleUpperCase('ru').split('')
  return runShape(chars, (ch) => LETTERS[ch], DIGIT_COLS, 1)
}

/** Буквы слова, которых нет в наборе (пробел не в счёт). */
export function missingLetters(text) {
  const chars = String(text).toLocaleUpperCase('ru').split('')
  return [...new Set(chars.filter((ch) => ch.trim() !== '' && !LETTERS[ch]))]
}

/**
 * Точки по периметру прямоугольника — обводка кнопки той же сеткой,
 * что и скобки. `radius = 0` даёт прямой угол, и это рабочий случай,
 * а не вырожденный.
 *
 * Углы считаются отдельно от сторон, и вот почему. Точка обязана стоять
 * ровно в углу: у прямоугольника угол — это то, чем он читается, и
 * пропущенная точка там видна сразу, тогда как лишняя тысячная доля
 * пикселя в шаге по стороне не видна никогда. Поэтому у прямого угла
 * шаг подгоняется на КАЖДОЙ стороне отдельно (узлы приходятся на углы),
 * и по горизонтали он может отличаться от вертикального на сотые доли.
 *
 * У скруглённого угла угла как точки не существует, там непрерывная дуга —
 * и шаг подгоняется один на весь периметр, иначе на стыке дуги и стороны
 * встал бы сдвоенный просвет.
 */
export function ringDots(w, h, radius) {
  const x0 = DOT_R
  const y0 = DOT_R
  const x1 = w - DOT_R
  const y1 = h - DOT_R
  const W = x1 - x0
  const H = y1 - y0
  if (W <= 0 || H <= 0) return []

  const rad = Math.max(0, Math.min(radius - DOT_R, Math.min(W, H) / 2))

  // Прямой угол: стороны считаются порознь, узлы садятся на углы.
  if (rad === 0) {
    const side = (from, to, keepLast) => {
      const len = Math.hypot(to[0] - from[0], to[1] - from[1])
      const n = Math.max(1, Math.round(len / DOT_STEP))
      const out = []
      for (let i = 0; i < (keepLast ? n + 1 : n); i += 1) {
        const k = i / n
        out.push([from[0] + (to[0] - from[0]) * k, from[1] + (to[1] - from[1]) * k])
      }
      return out
    }
    return [
      ...side([x0, y0], [x1, y0], false),
      ...side([x1, y0], [x1, y1], false),
      ...side([x1, y1], [x0, y1], false),
      ...side([x0, y1], [x0, y0], false),
    ]
  }

  const lineX = W - 2 * rad
  const lineY = H - 2 * rad
  const arc = (Math.PI * rad) / 2

  // Обход по часовой стрелке от верхнего левого скругления.
  const cx = { tr: x1 - rad, br: x1 - rad, bl: x0 + rad, tl: x0 + rad }
  const cy = { tr: y0 + rad, br: y1 - rad, bl: y1 - rad, tl: y0 + rad }

  const onArc = (k, from) => (t) => {
    const a = from + (rad > 0 ? t / rad : 0)
    return [cx[k] + rad * Math.cos(a), cy[k] + rad * Math.sin(a)]
  }

  const segments = [
    { len: lineX, at: (t) => [x0 + rad + t, y0] },
    { len: arc, at: onArc('tr', -Math.PI / 2) },
    { len: lineY, at: (t) => [x1, y0 + rad + t] },
    { len: arc, at: onArc('br', 0) },
    { len: lineX, at: (t) => [x1 - rad - t, y1] },
    { len: arc, at: onArc('bl', Math.PI / 2) },
    { len: lineY, at: (t) => [x0, y1 - rad - t] },
    { len: arc, at: onArc('tl', Math.PI) },
  ]

  const perimeter = segments.reduce((s, seg) => s + seg.len, 0)
  if (perimeter <= 0) return []

  const count = Math.max(4, Math.round(perimeter / DOT_STEP))
  const step = perimeter / count

  const dots = []
  let seg = 0
  let base = 0
  for (let i = 0; i < count; i += 1) {
    const d = i * step
    while (seg < segments.length - 1 && d > base + segments[seg].len) {
      base += segments[seg].len
      seg += 1
    }
    dots.push(segments[seg].at(d - base))
  }
  return dots
}
